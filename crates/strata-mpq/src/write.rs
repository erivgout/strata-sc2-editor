//! Archive writing.
//!
//! Output layout (all offsets relative to the MPQ header):
//! `[optional MPQ\x1B user data, padded to 512][v4 header (208 bytes)]`
//! `[file data...][hash table][block table]`.
//!
//! The header is format v4 with only classic (encrypted) hash/block tables
//! (no HET/BET), carrying table sizes and the table + header MD5s. It must be
//! v4: StormLib treats any `.SC2Map` header newer than v2 as v4 and rejects
//! it with `ERROR_FAKE_MPQ_HEADER` unless the header MD5 is valid. Files up to one
//! sector are written as a single compressed unit and larger files as
//! sectors, each zlib-compressed when that makes it smaller -- the same
//! layout the SC2 editor produces. `(listfile)` and `(attributes)`
//! (CRC32 + MD5, like the SC2 editor) are generated. Output is deterministic:
//! files are ordered by case-insensitive name regardless of insertion order.

use std::collections::HashMap;

use crate::compress::compress_sector_zlib;
use crate::crypt::{
    encrypt, hash_string, HASH_NAME_A, HASH_NAME_B, HASH_TABLE_OFFSET, KEY_BLOCK_TABLE,
    KEY_HASH_TABLE,
};
use crate::{MpqError, FLAG_COMPRESS, FLAG_EXISTS, FLAG_SINGLE_UNIT};

const HEADER_SIZE_V4: usize = 0xD0;
const LISTFILE: &str = "(listfile)";
const ATTRIBUTES: &str = "(attributes)";

/// Builds a new MPQ archive (format v4, as SC2 expects) in memory.
pub struct ArchiveBuilder {
    files: Vec<(String, Vec<u8>)>,
    sector_shift: u16,
    level: u8,
    attributes: bool,
    user_data: Option<Vec<u8>>,
}

impl Default for ArchiveBuilder {
    fn default() -> Self {
        ArchiveBuilder {
            files: Vec::new(),
            // 512 << 5 = 16 KiB sectors, what the SC2 editor writes.
            sector_shift: 5,
            level: 6,
            attributes: true,
            user_data: None,
        }
    }
}

struct Block {
    pos: u32,
    csize: u32,
    fsize: u32,
    flags: u32,
}

impl ArchiveBuilder {
    pub fn new() -> Self {
        Self::default()
    }

    /// Add a file; `/` separators are stored as `\`. Adding the same name
    /// again (case-insensitively) replaces the earlier data. `(listfile)` and
    /// `(attributes)` are generated by [`ArchiveBuilder::build`] and ignored here.
    pub fn add(&mut self, name: &str, data: Vec<u8>) {
        self.files.push((name.to_owned(), data));
    }

    /// Sector size as a shift: sector bytes = `512 << shift` (default 5).
    pub fn with_sector_size_shift(mut self, shift: u16) -> Self {
        self.sector_shift = shift.min(20);
        self
    }

    /// zlib level 0-10 (default 6). 0 stores all data uncompressed.
    pub fn with_compression_level(mut self, level: u8) -> Self {
        self.level = level.min(10);
        self
    }

    /// Whether to write `(attributes)` (default true).
    pub fn with_attributes(mut self, enabled: bool) -> Self {
        self.attributes = enabled;
        self
    }

    /// Prepend an `MPQ\x1B` user-data block (as Battle.net-published maps
    /// and replays have). The MPQ header is placed at the next 512-byte boundary.
    pub fn with_user_data(mut self, data: Vec<u8>) -> Self {
        self.user_data = Some(data);
        self
    }

    pub fn len(&self) -> usize {
        self.files.len()
    }

    pub fn is_empty(&self) -> bool {
        self.files.is_empty()
    }

    pub fn build(self) -> Result<Vec<u8>, MpqError> {
        let ArchiveBuilder {
            files,
            sector_shift,
            level,
            attributes,
            user_data,
        } = self;
        let sector_size = 512usize << sector_shift;

        // Normalise, de-duplicate (last wins) and sort.
        let mut by_key: HashMap<String, usize> = HashMap::new();
        let mut unique: Vec<Option<(String, Vec<u8>)>> = Vec::new();
        for (name, data) in files {
            let name = name.replace('/', "\\");
            let key = name.to_ascii_uppercase();
            if name.is_empty() || key == "(LISTFILE)" || key == "(ATTRIBUTES)" {
                continue;
            }
            if let Some(&i) = by_key.get(&key) {
                unique[i] = None;
            }
            by_key.insert(key, unique.len());
            unique.push(Some((name, data)));
        }
        let mut entries: Vec<(String, Vec<u8>)> = unique.into_iter().flatten().collect();
        entries.sort_by_cached_key(|(n, _)| n.to_ascii_uppercase());

        let mut listfile = Vec::new();
        for (name, _) in &entries {
            listfile.extend_from_slice(name.as_bytes());
            listfile.extend_from_slice(b"\r\n");
        }
        entries.push((LISTFILE.to_owned(), listfile));

        let total_files = entries.len() + attributes as usize;
        let hash_count = (total_files * 2).next_power_of_two().max(16);

        let mut out = Vec::new();
        let base = match &user_data {
            Some(ud) => (16 + ud.len()).next_multiple_of(512),
            None => 0,
        };
        let payload: usize = entries.iter().map(|(_, d)| d.len()).sum();
        out.reserve(
            base + HEADER_SIZE_V4 + payload + payload / 64 + hash_count * 16 + total_files * 16,
        );
        if let Some(ud) = &user_data {
            out.extend_from_slice(b"MPQ\x1B");
            out.extend_from_slice(&((base - 16) as u32).to_le_bytes());
            out.extend_from_slice(&(base as u32).to_le_bytes());
            out.extend_from_slice(&(ud.len() as u32).to_le_bytes());
            out.extend_from_slice(ud);
            out.resize(base, 0);
        }
        out.resize(base + HEADER_SIZE_V4, 0);

        let mut blocks = Vec::with_capacity(total_files);
        let mut crcs = Vec::with_capacity(total_files);
        let mut md5s = Vec::with_capacity(total_files);
        let mut names: Vec<String> = Vec::with_capacity(total_files);
        for (name, data) in &entries {
            blocks.push(write_file(&mut out, base, data, sector_size, level)?);
            if attributes {
                crcs.push(crc32fast::hash(data));
                md5s.push(crate::attributes::md5(data));
            }
            names.push(name.clone());
        }
        if attributes {
            // (attributes) cannot checksum itself; its entry is left zeroed.
            crcs.push(0);
            md5s.push([0; 16]);
            let attr = crate::attributes::build(&crcs, &md5s);
            blocks.push(write_file(&mut out, base, &attr, sector_size, level)?);
            names.push(ATTRIBUTES.to_owned());
        }

        // Hash table.
        let mut hash = vec![0xFFu8; hash_count * 16];
        for (block, name) in names.iter().enumerate() {
            let mut slot = hash_string(name, HASH_TABLE_OFFSET) as usize & (hash_count - 1);
            while u32::from_le_bytes(hash[slot * 16 + 12..slot * 16 + 16].try_into().unwrap())
                != 0xFFFF_FFFF
            {
                slot = (slot + 1) & (hash_count - 1);
            }
            let e = &mut hash[slot * 16..slot * 16 + 16];
            e[0..4].copy_from_slice(&hash_string(name, HASH_NAME_A).to_le_bytes());
            e[4..8].copy_from_slice(&hash_string(name, HASH_NAME_B).to_le_bytes());
            e[8..12].copy_from_slice(&0u32.to_le_bytes()); // locale + platform
            e[12..16].copy_from_slice(&(block as u32).to_le_bytes());
        }
        encrypt(&mut hash, KEY_HASH_TABLE);
        let hash_pos = rel(&out, base)?;
        out.extend_from_slice(&hash);

        let mut table = Vec::with_capacity(blocks.len() * 16);
        for b in &blocks {
            for v in [b.pos, b.csize, b.fsize, b.flags] {
                table.extend_from_slice(&v.to_le_bytes());
            }
        }
        encrypt(&mut table, KEY_BLOCK_TABLE);
        let block_pos = rel(&out, base)?;
        out.extend_from_slice(&table);
        let archive_size = rel(&out, base)?;

        let h = &mut out[base..base + HEADER_SIZE_V4];
        h[0x00..0x04].copy_from_slice(b"MPQ\x1A");
        h[0x04..0x08].copy_from_slice(&(HEADER_SIZE_V4 as u32).to_le_bytes());
        h[0x08..0x0C].copy_from_slice(&archive_size.to_le_bytes());
        h[0x0C..0x0E].copy_from_slice(&3u16.to_le_bytes()); // format v4
        h[0x0E..0x10].copy_from_slice(&sector_shift.to_le_bytes());
        h[0x10..0x14].copy_from_slice(&hash_pos.to_le_bytes());
        h[0x14..0x18].copy_from_slice(&block_pos.to_le_bytes());
        h[0x18..0x1C].copy_from_slice(&(hash_count as u32).to_le_bytes());
        h[0x1C..0x20].copy_from_slice(&(blocks.len() as u32).to_le_bytes());
        // 0x20..0x2C: hi-block table pos (0), hash/block pos high words (0).
        h[0x2C..0x34].copy_from_slice(&(archive_size as u64).to_le_bytes());
        // 0x34..0x44: BET/HET positions (0 = absent).
        h[0x44..0x4C].copy_from_slice(&(hash.len() as u64).to_le_bytes());
        h[0x4C..0x54].copy_from_slice(&(table.len() as u64).to_le_bytes());
        // 0x54..0x6C: hi-block/HET/BET sizes (0); 0x6C: raw chunk size (0 = no
        // per-chunk MD5s after file data).
        h[0x70..0x80].copy_from_slice(&crate::attributes::md5(&table));
        h[0x80..0x90].copy_from_slice(&crate::attributes::md5(&hash));
        // 0x90..0xC0: hi-block/BET/HET MD5s (zero = absent).
        let header_md5 = crate::attributes::md5(&h[..0xC0]);
        h[0xC0..0xD0].copy_from_slice(&header_md5);
        Ok(out)
    }
}

fn rel(out: &[u8], base: usize) -> Result<u32, MpqError> {
    u32::try_from(out.len() - base)
        .map_err(|_| MpqError::Unsupported("archives over 4 GiB cannot be written".into()))
}

fn write_file(
    out: &mut Vec<u8>,
    base: usize,
    data: &[u8],
    sector_size: usize,
    level: u8,
) -> Result<Block, MpqError> {
    let start = out.len();
    let pos = rel(out, base)?;
    let fsize = u32::try_from(data.len())
        .map_err(|_| MpqError::Unsupported("files over 4 GiB cannot be written".into()))?;
    if data.is_empty() {
        return Ok(Block {
            pos,
            csize: 0,
            fsize: 0,
            flags: FLAG_EXISTS,
        });
    }
    let compress = |chunk: &[u8]| {
        (level > 0)
            .then(|| compress_sector_zlib(chunk, level))
            .flatten()
    };
    if data.len() <= sector_size {
        // Small files: one compressed unit, as the SC2 editor writes them.
        match compress(data) {
            Some(c) => out.extend_from_slice(&c),
            None => out.extend_from_slice(data),
        }
        return Ok(Block {
            pos,
            csize: (out.len() - start) as u32,
            fsize,
            flags: FLAG_EXISTS | FLAG_COMPRESS | FLAG_SINGLE_UNIT,
        });
    }
    // Larger files: sector offset table, then each sector compressed when
    // that makes it smaller (a sector of full length is read back raw).
    let sectors = data.len().div_ceil(sector_size);
    let table_len = (sectors + 1) * 4;
    out.resize(start + table_len, 0);
    let mut offset = table_len;
    out[start..start + 4].copy_from_slice(&(offset as u32).to_le_bytes());
    for (i, chunk) in data.chunks(sector_size).enumerate() {
        match compress(chunk) {
            Some(c) => out.extend_from_slice(&c),
            None => out.extend_from_slice(chunk),
        }
        offset = out.len() - start;
        let at = start + (i + 1) * 4;
        out[at..at + 4].copy_from_slice(&(offset as u32).to_le_bytes());
    }
    Ok(Block {
        pos,
        csize: offset as u32,
        fsize,
        flags: FLAG_EXISTS | FLAG_COMPRESS,
    })
}
